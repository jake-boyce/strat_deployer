export const getUnitById = (id: string): Unit | undefined => units.find((u) => u.id === id);

/** Every distinct faction represented in the unit roster, alphabetized.
 *  Drives the army selector on the disposition-picker page -- kept
 *  derived from `units` rather than hand-maintained so it can't drift
 *  out of sync as factions are added. */
export const factions: string[] = Array.from(
  new Set(units.map((u) => u.faction).filter((f): f is string => !!f))
).sort();

/** Which OTHER factions' units an army selection also gets access to,
 *  beyond its own -- e.g. Space Wolves is a Space Marines successor
 *  chapter fielded from the same core codex, so selecting it as an army
 *  should surface the generic Space Marines roster too, not just units
 *  explicitly tagged `faction: "Space Wolves"`. A faction not listed
 *  here (Space Marines itself, Tyranids, ...) only gets its own units.
 *  Per-unit exceptions to this (chapter-specific characters the shared
 *  codex doesn't actually cover) are handled separately via each unit's
 *  `excludedFromArmies`, not by narrowing this list. */
const armyFactionAccess: Record<string, string[]> = {
  "Space Wolves": ["Space Marines"],
};

/** The unit list to offer for a given army selection: the army's own
 *  faction, plus whatever `armyFactionAccess` grants access to, minus
 *  anything individually excluded for that army via
 *  `excludedFromArmies`. `army === null` (the "Any army" default) means
 *  no filtering at all -- the full roster, same as before this existed. */
export function unitsForArmy(army: string | null): Unit[] {
  if (!army) return units;
  const includableFactions = new Set([army, ...(armyFactionAccess[army] ?? [])]);
  return units.filter(
    (u) => u.faction !== undefined && includableFactions.has(u.faction) && !u.excludedFromArmies?.includes(army)
  );
}
